# Builds the new families' attack effects for the game.
# Sources: tools/new_art/vfx/<id>.png + <id>.json (an export of PixelLab's effects tool: a sheet of whole
# frames and where each is) + <id>.meta.json ({"kind", "hit"}: what the effect is and the frame its attack lands).
# Writes, for every effect:
#   assets/sprites/vfx/new/<id>.png   its frames, each trimmed to what it draws, packed in rows
# and the VFX_NEW block at the end of src/content/vfx_data.js (frames: [x, y, w, h, offset x, offset y] in
# that picture, null = an empty frame). The game fetches a picture the first time its effect is needed
# (gfx/art.js warmVfx). Run it again whenever a source changes:
#   python tools/pack_vfx_new.py
import glob, json, os, re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'new_art', 'vfx')
OUT = os.path.join(ROOT, 'assets', 'sprites', 'vfx', 'new')
DATA = os.path.join(ROOT, 'src', 'content', 'vfx_data.js')
LOOPS = {'glob', 'zone', 'proj', 'spinproj', 'missile'}
ROW = 1024  # a picture is at most this wide
MARK = '// ---- the new families\' effects'

os.makedirs(OUT, exist_ok=True)
entries, total = {}, 0
for meta_path in sorted(glob.glob(os.path.join(SRC, '*.meta.json'))):
    i = os.path.basename(meta_path)[:-len('.meta.json')]
    meta = json.load(open(meta_path, encoding='utf-8'))
    d = json.load(open(os.path.join(SRC, i + '.json'), encoding='utf-8'))
    sheet = Image.open(os.path.join(SRC, i + '.png')).convert('RGBA')
    frames = [sheet.crop((f['frame']['x'], f['frame']['y'], f['frame']['x'] + f['frame']['w'], f['frame']['y'] + f['frame']['h'])) for f in d['frames']]
    w, h = frames[0].size
    a = d['meta'].get('anchor') or {}
    ax = a.get('x', round(d['frames'][0]['pivot']['x'] * w)); ay = a.get('y', round(d['frames'][0]['pivot']['y'] * h))
    # trim each frame, then lay them out in rows
    cuts = []
    for fr in frames:
        b = fr.getbbox()
        cuts.append((fr.crop(b), b[0], b[1]) if b else None)
    x = y = row = 0; place = []
    for c in cuts:
        if not c: place.append(None); continue
        im = c[0]
        if x + im.width > ROW: x, y, row = 0, y + row + 1, 0
        place.append((x, y)); x += im.width + 1; row = max(row, im.height)
    W = max((p[0] + c[0].width for p, c in zip(place, cuts) if p), default=1); H = y + row
    out = Image.new('RGBA', (W, max(H, 1)), (0, 0, 0, 0)); f = []
    for p, c in zip(place, cuts):
        if not p: f.append(None); continue
        out.paste(c[0], p); f.append([p[0], p[1], c[0].width, c[0].height, c[1], c[2]])
    out.save(os.path.join(OUT, i + '.png'), optimize=True)
    total += os.path.getsize(os.path.join(OUT, i + '.png'))
    kind = meta.get('kind') or 'fx'
    entries[i] = {'fps': round(1000 / d['frames'][0]['duration'], 2), 'loop': kind in LOOPS, 'ax': ax, 'ay': ay, 'w': w, 'h': h,
                  'hit': None if kind in LOOPS else meta.get('hit'), 'kind': kind, 'f': f}
# pictures of effects that no longer have a source go away
for p in glob.glob(os.path.join(OUT, '*.png')):
    if os.path.basename(p)[:-4] not in entries: os.remove(p)

js = open(DATA, encoding='utf-8').read().replace('\r\n', '\n')
if MARK in js: js = js[:js.index(MARK)].rstrip('\n') + '\n'
block = (MARK + ' (generated by tools/pack_vfx_new.py: do not edit by hand).\n'
         '// Each is its own picture, assets/sprites/vfx/new/<id>.png, fetched the first time it is needed.\n'
         '// f = frames: [x, y, w, h, offset x, offset y] in that picture (null = empty frame); the rest as above.\n'
         'export const VFX_NEW = {\n'
         + ''.join(f'  {i}: {json.dumps(e, separators=(",", ":"))},\n' for i, e in entries.items())
         + '};\n')
open(DATA, 'w', encoding='utf-8', newline='\n').write(js + block)
kinds = {}
for e in entries.values(): kinds[e['kind']] = kinds.get(e['kind'], 0) + 1
print(f'{len(entries)} effects, {total // 1024} KB of pictures:', ', '.join(f'{n} {k}' for k, n in sorted(kinds.items())))
